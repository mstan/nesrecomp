/* Own HD job contract and integer blend rules. No guest memory is sampled. */
static const char hd_gpu_vertex[] =
    "#version 140\n"
    "void main(){vec2 p=vec2((gl_VertexID<<1)&2,gl_VertexID&2);"
    "gl_Position=vec4(p*2.0-1.0,0.0,1.0);}\n";

static const char hd_gpu_fragment[] =
    "#version 140\n"
    "uniform usampler2D jobs;\n"
    "uniform usampler2DArray source_pages;\n"
    "uniform usamplerBuffer page_map,images;\n"
    "uniform isampler2D backgrounds;\n"
    "uniform int output_scale,source_scale,image_count,under_end,mid_end,bg_count,hud_rows;\n"
    "out vec4 result;\n"
    "uvec3 rgb(uint c){return uvec3((c>>16u)&255u,(c>>8u)&255u,c&255u);}\n"
    "uint color(uvec3 c,uint a){return (a<<24u)|(c.r<<16u)|(c.g<<8u)|c.b;}\n"
    "uint bright(uint c,uint b){return color(min(uvec3(255u),rgb(c)*b/255u),c>>24u);}\n"
    "uint over(uint u,uint s){uint a=s>>24u;if(a==0u)return u;if(a==255u)return s;"
    "return color(min(uvec3(255u),rgb(s)+rgb(u)*(255u-a)/255u),255u);}\n"
    "uint sample_image(uint id,ivec2 p){uvec4 m=texelFetch(images,int(id));"
    "int cols=(int(m.y)+127)/128;"
    "uint slot=texelFetch(page_map,int(m.x)+(p.y/128)*cols+p.x/128).r;"
    "return texelFetch(source_pages,ivec3(p%128,int(slot)),0).r;}\n"
    "uint tile(uint u,uint mode,uint id,uint uv,uint fallback,uint flags,ivec2 sub){"
    "if(mode==0u)return u;if(mode==1u)return fallback;"
    "uvec4 m=texelFetch(images,int(id));int ox=int(uv&7u),oy=int((uv>>8u)&7u);"
    "if((flags&16u)!=0u){ox=7-ox;sub.x=source_scale-1-sub.x;}"
    "if((flags&32u)!=0u)sub.y=source_scale-1-sub.y;"
    "uint s=sample_image(id,ivec2(ox,oy)*source_scale+sub);"
    "return over(u,bright(s,m.w));}\n"
    "uint band(uint u,int first,int last,ivec2 native,ivec2 sub){"
    "for(int i=first;i<last;++i){ivec4 a=texelFetch(backgrounds,ivec2(0,i),0);"
    "ivec4 b=texelFetch(backgrounds,ivec2(1,i),0);"
    "uvec4 m=texelFetch(images,a.x);"
    "ivec2 p=(native+a.yz)*source_scale+sub;"
    "if(any(lessThan(p,ivec2(0)))||any(greaterThanEqual(p,ivec2(m.yz))))continue;"
    "uint s=bright(sample_image(uint(a.x),p),uint(a.w));if((s>>24u)==0u)continue;"
    "if(b.x==1)u=color(min(uvec3(255u),rgb(u)+rgb(s)),255u);"
    "else if(b.x==2)u=color(uvec3(max(ivec3(0),ivec3(rgb(u))-ivec3(rgb(s)))),255u);"
    "else u=over(u,s);}return u;}\n"
    "void main(){ivec2 p=ivec2(gl_FragCoord.xy),n=p/output_scale;"
    "ivec2 sub=(p%output_scale)*source_scale/output_scale;"
    "uvec4 a=texelFetch(jobs,ivec2(n.x*2,n.y),0);"
    "uvec4 b=texelFetch(jobs,ivec2(n.x*2+1,n.y),0);"
    "uint u=a.x;if(n.y>=hud_rows)u=band(u,0,under_end,n,sub);"
    "u=tile(u,b.w&3u,a.y,a.z,a.w,0u,sub);"
    "u=band(u,under_end,mid_end,n,sub);"
    "u=tile(u,(b.w>>2u)&3u,b.x,b.y,b.z,b.w,sub);"
    "u=band(u,mid_end,bg_count,n,sub);"
    "result=vec4(vec3(rgb(u))/255.0,float(u>>24u)/255.0);}\n";
