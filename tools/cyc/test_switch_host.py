#!/usr/bin/env python3
"""ROM-free Switch host contracts, using SDL dummy drivers on the native host.

Also emits a prepared cross-build project: generated by the native compiler,
then compiled by a separate SDK (including Linux SDKs inside Docker).
"""
import argparse
import os
import re
from pathlib import Path
import subprocess


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--out', required=True, type=Path)
    ap.add_argument('--recompiler', required=True, type=Path)
    ap.add_argument('--pal', action='store_true', help='Use an NES 2.0 PAL header and check the reported region')
    ap.add_argument('--no-saves', action='store_true', help='Check that all save/load paths are disabled')
    args = ap.parse_args()
    root = Path(__file__).resolve().parents[2]
    out = args.out.resolve()
    data = out / 'data'
    data.mkdir(parents=True, exist_ok=True)
    (data / 'saves').mkdir(exist_ok=True)
    # Original test program: solid background, an incrementing CPU RAM byte,
    # and a fixed loop. No commercial ROM, code, graphics or audio assets.
    program = bytes.fromhex('78 d8 a2 ff 9a a9 00 8d 00 20 8d 01 20 '
                            'a9 3f 8d 06 20 a9 00 8d 06 20 a9 21 8d 07 20 '
                            'a9 08 8d 01 20 '
                            # Poll all eight NES controller bits into RAM $01.
                            'a9 01 8d 16 40 a9 00 8d 16 40 a2 08 '
                            'ad 16 40 4a 66 01 ca d0 f7 '
                            'e6 00 4c 21 80')
    prg = bytearray([0xea]) * 32768
    prg[:len(program)] = program
    prg[-6:] = bytes.fromhex('00 80 00 80 00 80')
    rom = data / 'rom.nes'
    header = bytearray(b'NES\x1a' + bytes([2, 1]) + bytes(10))
    if args.pal:
        header[7] = 8  # NES 2.0 carries an authoritative regional timing mode.
        header[12] = 1
    rom.write_bytes(header + prg + bytes(8192))
    config = out / 'vanilla.toml'
    config.write_text('[game]\ncycle_accurate=true\n', encoding='utf-8')

    def run(command, name, success=True, env=None):
        result = subprocess.run(list(map(str, command)), capture_output=True, text=True,
                                env=env, timeout=600)
        (out / (name + '.log')).write_text(result.stdout + result.stderr, encoding='utf-8')
        assert (result.returncode == 0) == success, (name, result.returncode, result.stdout[-1000:], result.stderr[-2000:])
        return result

    prepared = out / 'prepared'
    run(['python3', root / 'tools/cyc/prepare_project.py', '--rom', rom, '--game', config,
         '--recompiler', args.recompiler.resolve(), '--out', prepared], 'prepare')
    source = out / 'project'
    source.mkdir(exist_ok=True)
    # The platform production entry point remains runner/cyc/project. This
    # harness reuses exactly the same core list and Mac-generated sources.
    (source / 'CMakeLists.txt').write_text(f'''cmake_minimum_required(VERSION 3.20)
project(SwitchHostContract C)
set(NESRECOMP_ROOT "{root.as_posix()}")
include("${{NESRECOMP_ROOT}}/runner/cyc/cyc.cmake")
include("{prepared.as_posix()}/sources.cmake")
add_executable(switch_fixture ${{NESRECOMP_CYC_SOURCES}} ${{CYC_PROJECT_SOURCES}})
target_include_directories(switch_fixture PRIVATE ${{NESRECOMP_CYC_INCLUDE_DIRS}})
target_compile_definitions(switch_fixture PRIVATE CYC_HOST_EXTRAS_STRONG=1
    NESRECOMP_NATIVE_INTERVALS=${{CYC_PROJECT_NATIVE_INTERVALS}})
target_link_libraries(switch_fixture PRIVATE ${{NESRECOMP_CYC_LIBRARIES}})
if(NINTENDO_SWITCH)
    set(NESRECOMP_SWITCH_GAME_DIR "sdmc:/switch/nesrecomp/fixture")
    set(NESRECOMP_SWITCH_TITLE "NESRecomp test fixture")
    nesrecomp_cyc_enable_sdl(switch_fixture)
else()
    find_package(SDL2 CONFIG REQUIRED)
    get_target_property(sources switch_fixture SOURCES)
    list(REMOVE_ITEM sources "${{NESRECOMP_CYC_DIR}}/cyc_diagnostics.c")
    set_property(TARGET switch_fixture PROPERTY SOURCES "${{sources}}")
    target_sources(switch_fixture PRIVATE "${{NESRECOMP_ROOT}}/runner/switch/host.c"
        "${{NESRECOMP_ROOT}}/runner/switch/diagnostics.c")
    target_compile_definitions(switch_fixture PRIVATE CYC_WITH_SDL CYC_SWITCH
        CYC_SWITCH_VERSION="contract-test"
        CYC_SWITCH_SAVES={int(not args.no_saves)}
        CYC_SWITCH_GAME_DIR="{data.as_posix()}")
    target_link_libraries(switch_fixture PRIVATE SDL2::SDL2)
endif()
''', encoding='utf-8')
    binary = out / 'native'
    run(['cmake', '-S', source, '-B', binary, '-G', 'Ninja', '-DCMAKE_BUILD_TYPE=Release'], 'configure')
    run(['cmake', '--build', binary, '--parallel', '4'], 'build')
    env = dict(os.environ, SDL_VIDEODRIVER='dummy', SDL_AUDIODRIVER='dummy')
    exe = binary / 'switch_fixture'
    auto = data / 'saves/auto.cycstate'
    auto.unlink(missing_ok=True)
    if args.no_saves:
        # Existing broken state and even a non-directory saves path must be
        # ignored entirely by a no-save build. Also run beyond the old 30s
        # checkpoint to catch an accidentally retained periodic write.
        auto.write_bytes(b'preserved old state')
        run([exe, '--exit-after', '600', '--uncapped', '--nxlink-log'], 'no-saves-existing', env=env)
        launch_log = (data / 'runtime.log').read_text()
        assert 'network_log=off requested=1' in launch_log, launch_log
        assert auto.read_bytes() == b'preserved old state'
        save_dir = data / 'saves'; parked = data / 'parked-saves'
        save_dir.rename(parked); save_dir.write_text('not a directory')
        run([exe, '--exit-after', '1900'], 'no-saves-checkpoint', env=env)
        log = (data / 'runtime.log').read_text()
        assert 'Switch runner contract-test:' in log, log
        assert ('Region=PAL ' if args.pal else 'Region=NTSC ') in log, log
        assert 'saves=disabled' in log and 'saves=0' in log and 'Saved frame' not in log, log
        supply = re.findall(r'audio_supply produced_ms=([\d.]+) wall_ms=([\d.]+) ratio=([\d.]+)', log)
        assert supply and all(float(p) > 0 and float(w) > 0 for p, w, _ in supply), log
        assert all(0.9 < float(ratio) < 1.1 for _, _, ratio in supply), supply
        assert 'queue_empty_polls=' in log and 'source_rate=48000' in log, log
        assert save_dir.read_text() == 'not a directory'
        save_dir.unlink(); parked.rename(save_dir)
        # Repeated neutral-input benchmark runs must cover exactly 600 frames
        # after the same 300-frame warm-up and reach identical machine state.
        states = []
        for attempt in range(2):
            run([exe, '--benchmark', '--exit-after', '900', '--uncapped'],
                f'benchmark-{attempt}', env=env)
            benchmark_log = (data / 'runtime.log').read_text()
            assert 'warmup_frames=300 total_frames=900' in benchmark_log, benchmark_log
            assert 'frames=600 warmup_frames=300' in benchmark_log, benchmark_log
            assert 'interruptions=0 complete=1' in benchmark_log, benchmark_log
            states.append(re.search(r'benchmark_state mem=([0-9A-F]+) hw=([0-9A-F]+)', benchmark_log).groups())
        assert states[0] == states[1], states
        route = out / 'input.txt'
        route.write_text('0 START\n120 -\n400 RIGHT+B\n700 RIGHT+A\n')
        run([exe, rom, '--input', route, '--frames', '900', '--hash-out', out / 'route-hashes.txt',
             '--no-save'], 'route-headless', env=env)
        expected = dict(re.findall(r'(mem|hw)=([0-9A-F]+)', (out / 'route-hashes.txt').read_text().splitlines()[-1]))
        run([exe, '--window-input', route, '--benchmark', '--benchmark-warmup', '600',
             '--exit-after', '900', '--uncapped'], 'route-window', env=env)
        replay_log = (data / 'runtime.log').read_text()
        actual = re.search(r'benchmark_state mem=([0-9A-F]+) hw=([0-9A-F]+)', replay_log).groups()
        assert actual == (expected['mem'], expected['hw']), (actual, expected)
        assert actual != states[0], 'Fixture route must affect observable machine state'
        assert 'frames=300 warmup_frames=600 total_frames=900' in replay_log, replay_log
        assert 'input=scripted replay_frames=900' in replay_log and 'complete=1' in replay_log, replay_log
        assert 'saves=0' in replay_log and auto.read_bytes() == b'preserved old state'
        print('Switch no-save host: ignored old state and invalid save directory; 1900 paced frames passed without checkpoint or exit saves')
        print(f'Prepared cross-build source: {source}')
        return
    run([exe, '--exit-after', '600', '--uncapped'], 'boot', env=env)
    assert auto.stat().st_size > 100
    log = (data / 'runtime.log').read_text()
    assert 'Switch runner contract-test:' in log, log
    assert 'Saved frame 600' in log and 'interp_rom=0' in log, log
    first_state = auto.read_bytes()
    run([exe, '--exit-after', '600', '--uncapped'], 'resume', env=env)
    log = (data / 'runtime.log').read_text()
    assert 'Saved frame 1200' in log, log
    # Missing ROM and different PRG must fail without touching the last save.
    saved = auto.read_bytes()
    original = rom.read_bytes()
    rom.unlink()
    run([exe, '--exit-after', '1'], 'missing-rom', success=False, env=env)
    wrong = bytearray(original); wrong[17] ^= 1
    rom.write_bytes(wrong)
    run([exe, '--exit-after', '1'], 'wrong-rom', success=False, env=env)
    assert auto.read_bytes() == saved
    rom.write_bytes(original)
    # An incompatible/corrupt auto state cannot be silently overwritten.
    auto.write_bytes(b'broken state')
    run([exe, '--exit-after', '1'], 'bad-state', success=False, env=env)
    assert auto.read_bytes() == b'broken state'
    auto.write_bytes(first_state)
    # Force a save-write error with a directory at the temporary filename.
    blocked = auto.with_suffix(auto.suffix + '.tmp')
    blocked.mkdir()
    run([exe, '--exit-after', '1', '--uncapped'], 'save-error', success=False, env=env)
    assert auto.read_bytes() == first_state
    if blocked.exists():
        blocked.rmdir()
    # A directory in place of saves must fail before emulation starts.
    save_dir = data / 'saves'; parked = data / 'parked-saves'
    save_dir.rename(parked); save_dir.write_text('not a directory')
    run([exe, '--exit-after', '1'], 'directory-error', success=False, env=env)
    save_dir.unlink(); parked.rename(save_dir)
    print('Switch host: SDL video/audio loop, 100% native fixture, autosave/resume, missing/wrong ROM, corrupt state, write-error preservation and directory-error checks passed')
    print(f'Prepared cross-build source: {source}')


if __name__ == '__main__':
    main()
